/**
 * Getting in.
 *
 * There are exactly three doors and no others:
 *   - redeem an invite code                     -> a new account
 *   - upgrade a legacy token                    -> the same account, real credential
 *   - self-signup, only when explicitly enabled -> a new account (dev only)
 *
 * There is no password, no email and no sign-in screen. A person redeems once, the
 * device keeps a signed session in the keychain, and that is the whole of it. The
 * account is the device until there is a reason for it not to be.
 */
import { Hono } from 'hono';
import { z } from 'zod';
import { adminSession, provisioningSession, tenantSession, authLookup } from '../db/client.js';
import { resolveCtx, Unauthorized, isLegacyToken } from '../auth.js';
import { env } from '../env.js';
import { log } from '../log.js';
import { mintInviteCode, mintToken, normaliseInviteCode, newSessionId } from '../tokens.js';

/**
 * Create tenant + user + first session. One tenant per person: it costs nothing and
 * it means every RLS policy in the system is doing real work rather than sorting
 * rows inside one shared bucket.
 */
async function provision(
  label: string,
  /** Generated by the caller when a code must be claimed atomically for this user. */
  userId = crypto.randomUUID(),
): Promise<{ token: string; userId: string; tenantId: string }> {
  const tenantId = await adminSession(async (db) => {
    const t = await db.query<{ id: string }>(
      'INSERT INTO tenants (name) VALUES ($1) RETURNING id',
      [label.slice(0, 64)],
    );
    return t.rows[0]!.id;
  });

  // Ids are generated by the caller, NOT with RETURNING. RETURNING needs a SELECT
  // policy to match the new row and during provisioning none does -- the isolation
  // policy compares against an unset app.tenant_id. Insert-only keeps the policy
  // surface minimal instead of widening one to make a convenience clause work.
  const sessionId = newSessionId();

  await provisioningSession(tenantId, async (db) => {
    await db.query(
      `INSERT INTO app_users (id, tenant_id, email, tier) VALUES ($1,$2,$3,'trial')`,
      [userId, tenantId, `${tenantId}@device.local`],
    );
    await db.query(
      `INSERT INTO device_sessions (id, tenant_id, user_id, label, expires_at)
       VALUES ($1,$2,$3,$4, now() + ($5 || ' days')::interval)`,
      [sessionId, tenantId, userId, label.slice(0, 64), String(env.SESSION_TTL_DAYS)],
    );
  });

  return { token: mintToken(sessionId), userId, tenantId };
}

const Redeem = z.object({
  code: z.string().min(4).max(32),
  label: z.string().max(64).optional(),
});

export const authRoutes = new Hono()
  /**
   * Redeem an invite. The code is claimed with a conditional UPDATE, so two devices
   * racing on the same code cannot both win -- one gets the row, the other gets
   * "already used", and the outcome does not depend on how fast either was.
   */
  .post('/v1/auth/redeem', async (c) => {
    const body = Redeem.safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: 'bad request' }, 400);

    const code = normaliseInviteCode(body.data.code);

    // Reserved BEFORE the account exists, so two devices racing on one code cannot
    // both win -- the conditional UPDATE decides it, not whoever is faster. The id is
    // minted here for that reason, and `reserved_for` is deliberately not a foreign
    // key: at this instant it names an account that has not been created yet.
    const userId = crypto.randomUUID();
    const claimed = await adminSession(async (db) => {
      const { rows } = await db.query<{ note: string }>(
        `UPDATE invites SET reserved_for = $2, reserved_at = now()
          WHERE code = $1 AND reserved_for IS NULL AND expires_at > now()
        RETURNING note`,
        [code, userId],
      );
      return rows[0];
    });

    if (!claimed) {
      // One message for expired, used and never-existed. Distinguishing them turns
      // this into an oracle for guessing codes.
      return c.json({ error: 'invalid code', message: 'That code does not work. Ask for a new one.' }, 400);
    }

    let provisioned;
    try {
      provisioned = await provision(body.data.label ?? 'device', userId);
    } catch (err) {
      // Release it. A failed provision must not silently eat somebody's only invite.
      await adminSession((db) =>
        db.query(
          `UPDATE invites SET reserved_for = NULL, reserved_at = NULL
            WHERE code = $1 AND reserved_for = $2 AND used_by IS NULL`,
          [code, userId],
        ),
      ).catch((e: unknown) => log.error({ err: e, code }, 'invite not released'));
      throw err;
    }

    // Now the account exists, so the real reference can be written. Best-effort: the
    // person is already in, and failing their signup to record an audit column would
    // be the wrong trade.
    await adminSession((db) =>
      db.query(`UPDATE invites SET used_by = $1, used_at = now() WHERE code = $2`,
        [provisioned.userId, code]),
    ).catch((e: unknown) => log.error({ err: e, code }, 'invite attribution not recorded'));

    log.info({ userId: provisioned.userId, code }, 'invite redeemed');
    return c.json({ token: provisioned.token, note: claimed.note });
  })

  /**
   * Trade the old unsigned credential for a real session, once, without losing the
   * account behind it. Without this, closing signup would strand every device that
   * already holds a legacy token -- including the founder's, which carries all the
   * dogfooding data the eval corpus depends on.
   */
  .post('/v1/auth/upgrade', async (c) => {
    const header = c.req.header('authorization');
    if (!isLegacyToken(header)) {
      return c.json({ error: 'not a legacy token' }, 400);
    }
    let ctx;
    try {
      ctx = await resolveCtx(header);
    } catch (err) {
      if (err instanceof Unauthorized) return c.json({ error: 'unauthorized' }, 401);
      throw err;
    }

    const sessionId = newSessionId();
    await tenantSession(ctx, (db) =>
      db.query(
        `INSERT INTO device_sessions (id, tenant_id, user_id, label, expires_at)
         VALUES ($1,$2,$3,'upgraded device', now() + ($4 || ' days')::interval)`,
        [sessionId, ctx.tenantId, ctx.userId, String(env.SESSION_TTL_DAYS)],
      ),
    );

    log.info({ userId: ctx.userId }, 'legacy token upgraded');
    return c.json({ token: mintToken(sessionId) });
  })

  /** Dev only. Left in because turning it on is how the founder's own devices start. */
  .post('/v1/auth/device', async (c) => {
    if (!env.ALLOW_DEVICE_SIGNUP) {
      return c.json({ error: 'invite required', message: 'You need an invite code.' }, 403);
    }
    const body = (await c.req.json().catch(() => ({}))) as { label?: string };
    const provisioned = await provision(body.label ?? 'device');
    log.info({ userId: provisioned.userId }, 'device self-provisioned');
    return c.json({ token: provisioned.token, tenantId: provisioned.tenantId });
  });

/** Invites a signed-in person can hand out. Scarce on purpose. */
export const inviteRoutes = new Hono()
  .get('/v1/invites', async (c) => {
    let ctx;
    try {
      ctx = await resolveCtx(c.req.header('authorization'));
    } catch (err) {
      if (err instanceof Unauthorized) return c.json({ error: 'unauthorized' }, 401);
      throw err;
    }
    // Read through the owner pool: `invites` carries no RLS because a code must be
    // claimable by someone who is not yet anybody. The WHERE clause is the boundary,
    // and it is the only place this table is read by creator.
    const rows = await adminSession(async (db) => {
      const r = await db.query(
        `SELECT code, note, created_at, expires_at, (reserved_for IS NOT NULL) AS used
           FROM invites WHERE created_by = $1 ORDER BY created_at DESC LIMIT 50`,
        [ctx.userId],
      );
      return r.rows;
    });
    return c.json({ invites: rows, remaining: Math.max(0, env.INVITES_PER_USER - rows.filter((r) => !r.used).length) });
  })

  .post('/v1/invites', async (c) => {
    let ctx;
    try {
      ctx = await resolveCtx(c.req.header('authorization'));
    } catch (err) {
      if (err instanceof Unauthorized) return c.json({ error: 'unauthorized' }, 401);
      throw err;
    }
    const body = (await c.req.json().catch(() => ({}))) as { note?: string };

    const result = await adminSession(async (db) => {
      const { rows: open } = await db.query<{ n: string }>(
        `SELECT count(*) AS n FROM invites
          WHERE created_by = $1 AND reserved_for IS NULL AND expires_at > now()`,
        [ctx.userId],
      );
      if (Number(open[0]!.n) >= env.INVITES_PER_USER) return null;

      const code = mintInviteCode();
      await db.query(
        `INSERT INTO invites (code, created_by, note, expires_at)
         VALUES ($1,$2,$3, now() + ($4 || ' days')::interval)`,
        [code, ctx.userId, (body.note ?? '').slice(0, 200), String(env.INVITE_TTL_DAYS)],
      );
      return code;
    });

    if (!result) {
      return c.json({
        error: 'no invites left',
        message: `You can have ${env.INVITES_PER_USER} out at a time. Wait for one to be used.`,
      }, 429);
    }
    return c.json({ code: result, expiresInDays: env.INVITE_TTL_DAYS });
  });
