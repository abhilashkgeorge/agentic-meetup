/**
 * Getting in.
 *
 * There are exactly three doors and no others:
 *   - redeem an invite code                     -> a new account
 *   - upgrade a legacy token                    -> the same account, real credential
 *   - self-signup, only when explicitly enabled -> a new account (dev only)
 *
 * There is no password, no email and no sign-in screen. A person redeems once, the
 * device keeps a signed session in the keychain, and that is the whole of it. The
 * account is the device until there is a reason for it not to be.
 */
import { Hono } from 'hono';
import { LIMITS, rateLimit, take, callerIp } from '../ratelimit.js';
import { z } from 'zod';
import {
  adminSession, provisioningSession, tenantSession, authLookup, phoneSession,
} from '../db/client.js';
import { resolveCtx, Unauthorized, isLegacyToken } from '../auth.js';
import { env } from '../env.js';
import { log } from '../log.js';
import { mintInviteCode, mintToken, normaliseInviteCode, newSessionId, verifyToken } from '../tokens.js';
import { codeHmac, hashesMatch, newCode, phoneHmac } from '../phone.js';
import { sendCode } from '../sms.js';
import {
  OTP_MAX_ATTEMPTS, OTP_TTL_SEC, TICKET_TTL_SEC,
  maskPhone, normalisePhone,
} from '@clone/shared';

/** Parsed once. See SMS_COUNTRIES. */
const SMS_COUNTRIES = env.SMS_COUNTRIES.split(',').map((x) => x.trim()).filter(Boolean);

/**
 * Create tenant + user + first session. One tenant per person: it costs nothing and
 * it means every RLS policy in the system is doing real work rather than sorting
 * rows inside one shared bucket.
 */
async function provision(
  label: string,
  /** Generated by the caller when a code must be claimed atomically for this user. */
  userId = crypto.randomUUID(),
  /**
   * The verified number this account belongs to, already hashed.
   *
   * Written in the SAME insert as the account rather than in an update afterwards.
   * A second statement can fail, and an account with no number is exactly the thing
   * the unique index cannot catch later -- it would leave a person able to make a
   * second account with the number that was supposed to stop them.
   */
  phone?: string,
): Promise<{ token: string; userId: string; tenantId: string }> {
  // The id is generated HERE, not with RETURNING, for the same reason the app_users
  // insert below does it -- and now for a second reason as well.
  //
  // RETURNING needs SELECT on the table, and `tenants` carries no row-level security,
  // so granting the application SELECT on it means the application can list every
  // tenant that exists. 0039 revoked that; this is the shape that does not need it
  // back. INSERT alone is enough when nothing has to be read afterwards.
  const tenantId = crypto.randomUUID();
  await adminSession((db) =>
    db.query(
      'INSERT INTO tenants (id, name) VALUES ($1, $2)',
      [tenantId, label.slice(0, 64)],
    ));

  // Ids are generated by the caller, NOT with RETURNING. RETURNING needs a SELECT
  // policy to match the new row and during provisioning none does -- the isolation
  // policy compares against an unset app.tenant_id. Insert-only keeps the policy
  // surface minimal instead of widening one to make a convenience clause work.
  const sessionId = newSessionId();

  await provisioningSession(tenantId, async (db) => {
    await db.query(
      `INSERT INTO app_users (id, tenant_id, email, tier, phone_hmac, phone_verified_at)
       VALUES ($1,$2,$3,'trial',$4, CASE WHEN $4::text IS NULL THEN NULL ELSE now() END)`,
      [userId, tenantId, `${tenantId}@device.local`, phone ?? null],
    );
    await db.query(
      `INSERT INTO device_sessions (id, tenant_id, user_id, label, expires_at)
       VALUES ($1,$2,$3,$4, now() + ($5 || ' days')::interval)`,
      [sessionId, tenantId, userId, label.slice(0, 64), String(env.SESSION_TTL_DAYS)],
    );
  });

  return { token: mintToken(sessionId), userId, tenantId };
}

const Redeem = z.object({
  code: z.string().min(4).max(32),
  label: z.string().max(64).optional(),
  /** The verified-number ticket from /v1/auth/phone/verify. See the route. */
  ticket: z.uuid().optional(),
});

const StartPhone = z.object({
  phone: z.string().min(4).max(24),
  /** Assumed for a number typed without a `+`. Never guessed when absent. */
  country: z.string().max(5).optional(),
});

const VerifyPhone = z.object({
  challengeId: z.uuid(),
  code: z.string().min(4).max(8),
  label: z.string().max(64).optional(),
});

/**
 * Spend a verified-number ticket, or refuse.
 *
 * One statement, because the alternative is a read followed by a write and those two
 * can be run twice concurrently -- which is a ticket spent twice, which is two
 * accounts for one number, which is the whole thing this feature exists to prevent.
 * The conditional UPDATE lets the database decide the winner.
 */
async function spendTicket(db: import('pg').PoolClient, id: string): Promise<string | null> {
  const { rows } = await db.query<{ phone_hmac: string }>(
    `UPDATE phone_challenges SET consumed_at = now()
      WHERE id = $1 AND verified_at IS NOT NULL AND consumed_at IS NULL AND expires_at > now()
    RETURNING phone_hmac`,
    [id],
  );
  return rows[0]?.phone_hmac ?? null;
}

export const authRoutes = new Hono()
  /**
   * Redeem an invite. The code is claimed with a conditional UPDATE, so two devices
   * racing on the same code cannot both win -- one gets the row, the other gets
   * "already used", and the outcome does not depend on how fast either was.
   */
  .post('/v1/auth/redeem', rateLimit('redeem', LIMITS.redeem), async (c) => {
    const body = Redeem.safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: 'bad request' }, 400);

    const code = normaliseInviteCode(body.data.code);

    // THE NUMBER IS CHECKED BEFORE THE CODE IS SPENT.
    //
    // An invite is a scarce thing somebody handed out personally, and burning one on
    // a request that was always going to fail is the kind of small unfairness nobody
    // ever gets an explanation for. So the ticket is spent first: if the number is
    // not verified, or the ticket has already been used, the invite is untouched.
    let phone: string | null = null;
    if (!env.ALLOW_UNVERIFIED_SIGNUP) {
      if (!body.data.ticket) {
        return c.json({
          error: 'phone_required',
          message: 'Verify your phone number first.',
        }, 400);
      }
      phone = await phoneSession((db) => spendTicket(db, body.data.ticket!));
      if (!phone) {
        return c.json({
          error: 'ticket_expired',
          message: 'That took too long. Ask for a new code.',
        }, 400);
      }
    }

    // Reserved BEFORE the account exists, so two devices racing on one code cannot
    // both win -- the conditional UPDATE decides it, not whoever is faster. The id is
    // minted here for that reason, and `reserved_for` is deliberately not a foreign
    // key: at this instant it names an account that has not been created yet.
    const userId = crypto.randomUUID();
    const claimed = await adminSession(async (db) => {
      const { rows } = await db.query<{ note: string }>(
        `UPDATE invites SET reserved_for = $2, reserved_at = now()
          WHERE code = $1 AND reserved_for IS NULL AND expires_at > now()
        RETURNING note`,
        [code, userId],
      );
      return rows[0];
    });

    if (!claimed) {
      // One message for expired, used and never-existed. Distinguishing them turns
      // this into an oracle for guessing codes.
      return c.json({ error: 'invalid code', message: 'That code does not work. Ask for a new one.' }, 400);
    }

    let provisioned;
    try {
      provisioned = await provision(body.data.label ?? 'device', userId, phone ?? undefined);
    } catch (err) {
      // Release it. A failed provision must not silently eat somebody's only invite.
      await adminSession((db) =>
        db.query(
          `UPDATE invites SET reserved_for = NULL, reserved_at = NULL
            WHERE code = $1 AND reserved_for = $2 AND used_by IS NULL`,
          [code, userId],
        ),
      ).catch((e: unknown) => log.error({ err: e, code: `${code.slice(0, 4)}…` }, 'invite not released'));

      // The unique index on phone_hmac fired: this number got an account between
      // verifying and redeeming. Rare, and a 500 would be a lie -- nothing is broken,
      // they simply already have an account and should sign in instead.
      if ((err as { code?: string }).code === '23505') {
        log.warn({ code: `${code.slice(0, 4)}…` }, 'redeem lost the race for a number');
        return c.json({
          error: 'phone_taken',
          message: 'That number already has an account. Sign in with it instead.',
        }, 409);
      }
      throw err;
    }

    // Now the account exists, so the real reference can be written. Best-effort: the
    // person is already in, and failing their signup to record an audit column would
    // be the wrong trade.
    await adminSession((db) =>
      db.query(`UPDATE invites SET used_by = $1, used_at = now() WHERE code = $2`,
        [provisioned.userId, code]),
    ).catch((e: unknown) => log.error({ err: e, code: `${code.slice(0, 4)}…` }, 'invite attribution not recorded'));

    // The CODE IS A LIVE CREDENTIAL until it is claimed, and a log line is read by
    // everyone with dashboard access and kept as long as the retention policy says.
    // Enough of it to match a support question, not enough to redeem.
    log.info({ userId: provisioned.userId, code: `${code.slice(0, 4)}…` }, 'invite redeemed');
    return c.json({ token: provisioned.token, note: claimed.note });
  })

  /**
   * Trade the old unsigned credential for a real session, once, without losing the
   * account behind it. Without this, closing signup would strand every device that
   * already holds a legacy token -- including the founder's, which carries all the
   * dogfooding data the eval corpus depends on.
   */
  .post('/v1/auth/upgrade', rateLimit('auth', LIMITS.auth), async (c) => {
    const header = c.req.header('authorization');
    if (!isLegacyToken(header)) {
      return c.json({ error: 'not a legacy token' }, 400);
    }
    let ctx;
    try {
      ctx = await resolveCtx(header);
    } catch (err) {
      if (err instanceof Unauthorized) return c.json({ error: 'unauthorized' }, 401);
      throw err;
    }

    const sessionId = newSessionId();
    await tenantSession(ctx, (db) =>
      db.query(
        `INSERT INTO device_sessions (id, tenant_id, user_id, label, expires_at)
         VALUES ($1,$2,$3,'upgraded device', now() + ($4 || ' days')::interval)`,
        [sessionId, ctx.tenantId, ctx.userId, String(env.SESSION_TTL_DAYS)],
      ),
    );

    log.info({ userId: ctx.userId }, 'legacy token upgraded');
    return c.json({ token: mintToken(sessionId) });
  })

  /**
   * "Text me a code."
   *
   * ANSWERS THE SAME WAY WHETHER THE NUMBER IS KNOWN OR NOT. That is the one property
   * this route has to hold on to: a different response, a different status, or even a
   * noticeably different delay for a number that has an account turns this into a
   * membership oracle. Somebody could then feed it a list of numbers and learn which
   * of their contacts is on a dating app, which is a far worse leak than anything the
   * code itself protects.
   *
   * So there is no lookup here at all. Whether an account exists is decided at verify
   * time, after the person has proved the number is theirs.
   */
  .post('/v1/auth/phone/start', rateLimit('otp-send', LIMITS.otpSend), async (c) => {
    const body = StartPhone.safeParse(await c.req.json().catch(() => null));
    if (!body.success) {
      const fields = body.error.issues.map((i) => i.path.join('.') || '(body)');
      return c.json({
        error: 'bad_request',
        message: `The app sent something wrong (${fields.join(', ')}).`,
      }, 400);
    }

    const e164 = normalisePhone(body.data.phone, body.data.country ?? '+91');
    if (!e164) {
      return c.json({
        error: 'bad_number',
        message: 'That does not look like a phone number. Include the country code.',
      }, 400);
    }

    // A COUNTRY WE HAVE AGREED TO PAY FOR.
    //
    // Without this the route accepts any number on earth, which is how SMS pumping
    // works: somebody buys premium numbers in a high-termination country, points a
    // script at a signup form that texts codes, and takes a cut of the carrier
    // revenue. The bill is ours. The per-number limit does not help, because they
    // have thousands of numbers. The app's own screen already offered three
    // countries; the server accepted all of them.
    if (!SMS_COUNTRIES.some((cc) => e164.startsWith(cc))) {
      log.warn({ cc: e164.slice(0, 4) }, 'sms refused: country not allowed');
      return c.json({
        error: 'country_not_supported',
        message: 'We cannot text that country yet.',
      }, 400);
    }

    // THE LAST LINE, and the only one that does not care who is asking. Per-IP is
    // defeatable by spreading across hosts and per-number by using more numbers; a
    // global daily count is defeatable by neither, which is exactly what a spend cap
    // has to be.
    if (!take('sms:global', { max: env.SMS_DAILY_CAP, windowMs: 24 * 60 * 60_000 }).ok) {
      log.error({ cap: env.SMS_DAILY_CAP }, 'DAILY SMS CAP REACHED -- no more codes today');
      return c.json({
        error: 'unavailable',
        message: 'We cannot send codes right now. Try later.',
      }, 503);
    }

    // PER NUMBER, not just per IP. The IP limit above stops one machine hammering the
    // route; this stops a botnet spending our SMS budget on one person's phone, and
    // stops that person being woken up sixty times. Keyed on the hash so the limiter's
    // memory is not a list of who has tried to sign in.
    const hmac = phoneHmac(e164);
    const perPhone = take(`otp-phone:${hmac}`, LIMITS.otpSendPerPhone);
    if (!perPhone.ok) {
      return c.json(
        { error: 'too_many_requests', message: 'Too many codes. Wait a few minutes.' },
        429,
        { 'Retry-After': String(perPhone.retryAfterSec) },
      );
    }

    const code = newCode();
    const challengeId = await phoneSession(async (db) => {
      // Older challenges for this number die now. Without this, a code sent ten
      // minutes ago is still live alongside the new one, so "resend" quietly doubles
      // the number of valid codes instead of replacing the old one.
      await db.query(
        `UPDATE phone_challenges SET consumed_at = now()
          WHERE phone_hmac = $1 AND consumed_at IS NULL AND verified_at IS NULL`,
        [hmac],
      );
      // Opportunistic sweep of everybody's dead rows, on the one route that is
      // already paying for a write. A table of expired code hashes has no job and no
      // reason to be kept, and a cron for it would be a moving part to forget.
      // BOUNDED. Unqualified, this is a full-table DELETE inside the request's own
      // transaction: the first request after a flood pays for every row the flood
      // wrote, holding a connection on a two-connection pool while it does. A fixed
      // ceiling makes the cost of this line the same on every request.
      await db.query(
        `DELETE FROM phone_challenges WHERE ctid IN (
           SELECT ctid FROM phone_challenges
            WHERE expires_at < now() - interval '1 day' LIMIT 500)`);
      const { rows } = await db.query<{ id: string }>(
        `INSERT INTO phone_challenges (phone_hmac, code_hmac, expires_at, created_ip)
         VALUES ($1, 'pending', now() + ($2::int * interval '1 second'), $3)
         RETURNING id`,
        [hmac, OTP_TTL_SEC, callerIp(c.req.raw.headers)],
      );
      const id = rows[0]!.id;
      // The hash binds the code to THIS row, so the id has to exist first. See phone.ts.
      await db.query(`UPDATE phone_challenges SET code_hmac = $2 WHERE id = $1`,
        [id, codeHmac(id, code)]);
      return id;
    });

    const sent = await sendCode(e164, code);
    // Deliberately not surfaced as a failure. The row is written and a resend costs
    // nothing; telling somebody their number is broken because a provider hiccuped is
    // worse than letting them tap resend.
    if (!sent.ok) log.warn({ challengeId }, 'code not delivered');

    return c.json({
      challengeId,
      expiresInSec: OTP_TTL_SEC,
      sentTo: maskPhone(e164),
      // ONLY when the operator has explicitly turned the protection off. Named so
      // that it is obvious in a response body what has happened.
      ...(env.SMS_DEV_ECHO ? { devCode: code, devEchoIsOn: true } : {}),
    });
  })

  /**
   * "Here is the code."
   *
   * Three outcomes, and which one you get depends on what the number turns out to be:
   *
   *   linked      the caller was already signed in, so the number is attached to the
   *               account they are already using. Their token does not change.
   *   signed_in   the number belongs to an account. A new device session is issued
   *               for it -- this is the whole recovery story, and the only way a
   *               second phone joins an existing clone.
   *   needs_invite  nobody has this number yet. The ticket is handed back and the
   *               invite screen is next.
   */
  .post('/v1/auth/phone/verify', rateLimit('otp-verify', LIMITS.otpVerify), async (c) => {
    const body = VerifyPhone.safeParse(await c.req.json().catch(() => null));
    if (!body.success) {
      // WHICH FIELD, IN THE LOG AND IN THE REPLY.
      //
      // This used to answer `{ error: 'bad request' }` with no message at all, and
      // the app falls back to "That code did not work" when a reply carries none --
      // so a malformed request and a wrong code were indistinguishable on screen.
      // Somebody typed a perfectly good code and was told the code was wrong.
      //
      // Field NAMES only. The values are a one-time code and a challenge id.
      const fields = body.error.issues.map((i) => i.path.join('.') || '(body)');
      log.warn({ fields }, 'phone verify: malformed request');
      return c.json({
        error: 'bad_request',
        message: `The app sent something wrong (${fields.join(', ')}). Ask for a new code.`,
      }, 400);
    }
    const { challengeId, code } = body.data;

    // ONE STATEMENT DOES THE COUNTING AND THE FETCHING.
    //
    // Reading the row, comparing, then writing the new attempt count would let N
    // requests race in together, all read `attempts = 4`, and all get a guess for the
    // price of one. Incrementing inside the WHERE means the database serialises them
    // and the fifth guess is the fifth guess however many arrive at once.
    const row = await phoneSession(async (db) => {
      const { rows } = await db.query<{
        phone_hmac: string; code_hmac: string; attempts: number; verified_at: string | null;
      }>(
        `UPDATE phone_challenges SET attempts = attempts + 1
          WHERE id = $1 AND consumed_at IS NULL AND expires_at > now() AND attempts < $2
        RETURNING phone_hmac, code_hmac, attempts, verified_at`,
        [challengeId, OTP_MAX_ATTEMPTS],
      );
      return rows[0] ?? null;
    });

    // Expired, already used, never existed, or out of guesses. One message for all
    // four: telling them which is telling an attacker which.
    if (!row) {
      return c.json({
        error: 'bad_code',
        message: 'That code did not work. Ask for a new one.',
      }, 400);
    }

    if (!hashesMatch(row.code_hmac, codeHmac(challengeId, code))) {
      const left = Math.max(0, OTP_MAX_ATTEMPTS - row.attempts);
      // The count of remaining guesses is safe to give away -- it is about this one
      // challenge, which the caller created -- and without it people retype a code
      // they have already burned.
      return c.json({
        error: 'bad_code',
        message: left > 0 ? `Not that one. ${left} tries left.` : 'Too many tries. Ask for a new code.',
        attemptsLeft: left,
      }, 400);
    }

    // Right code. From here the row stops being a code and becomes a ticket: a
    // longer clock, because finding the invite a friend sent takes longer than
    // reading a text.
    await phoneSession((db) =>
      db.query(
        `UPDATE phone_challenges
            SET verified_at = COALESCE(verified_at, now()),
                expires_at  = now() + ($2::int * interval '1 second')
          WHERE id = $1`,
        [challengeId, TICKET_TTL_SEC],
      ));

    const label = body.data.label ?? 'device';

    // CASE 1: already signed in. Attach the number to the account in hand.
    const header = c.req.header('authorization');
    if (header) {
      let ctx;
      try { ctx = await resolveCtx(header); } catch { ctx = null; }
      if (ctx) {
        try {
          const { rowCount } = await tenantSession(ctx, (db) =>
            db.query(
              `UPDATE app_users SET phone_hmac = $2, phone_verified_at = now()
                WHERE id = $1 AND (phone_hmac IS NULL OR phone_hmac = $2)`,
              [ctx.userId, row.phone_hmac],
            ));
          if (!rowCount) {
            return c.json({
              error: 'already_linked',
              message: 'This account already uses a different number.',
            }, 409);
          }
        } catch (err) {
          if ((err as { code?: string }).code === '23505') {
            return c.json({
              error: 'phone_taken',
              message: 'That number belongs to another account.',
            }, 409);
          }
          throw err;
        }
        await phoneSession((db) => spendTicket(db, challengeId));
        log.info({ userId: ctx.userId }, 'phone linked to existing account');
        return c.json({ status: 'linked' });
      }
    }

    // CASE 2: the number already has an account. This is the recovery path.
    const owner = await phoneSession(async (db) => {
      const { rows } = await db.query<{ id: string; tenant_id: string }>(
        `SELECT id, tenant_id FROM app_users WHERE phone_hmac = $1`, [row.phone_hmac]);
      return rows[0] ?? null;
    });

    if (owner) {
      const ctx = { tenantId: owner.tenant_id, userId: owner.id };
      const sessionId = newSessionId();
      // WHETHER SETUP HAS EVER BEEN DONE, answered by the server rather than guessed
      // by the handset. "Onboarded" lives in the new device's own keychain and a new
      // device has an empty one, so without this a person signing in on their second
      // phone is walked through setup again -- asked their birth year by an agent
      // that already knows it. The account is the authority here, not the device.
      const onboarded = await tenantSession(ctx, async (db) => {
        const { rows } = await db.query<{ n: string }>(
          `SELECT count(*) AS n FROM predicate_status WHERE user_id = $1`, [ctx.userId]);
        return Number(rows[0]?.n ?? 0) > 0;
      });
      await tenantSession(ctx, (db) =>
        db.query(
          `INSERT INTO device_sessions (id, tenant_id, user_id, label, expires_at)
           VALUES ($1,$2,$3,$4, now() + ($5 || ' days')::interval)`,
          [sessionId, ctx.tenantId, ctx.userId, label.slice(0, 64), String(env.SESSION_TTL_DAYS)],
        ));
      await phoneSession((db) => spendTicket(db, challengeId));
      log.info({ userId: owner.id }, 'signed in by phone');
      return c.json({ status: 'signed_in', token: mintToken(sessionId), onboarded });
    }

    // CASE 3: a number nobody has. The invite screen is next, and the ticket is what
    // it will spend. Deliberately NOT consumed here.
    return c.json({ status: 'needs_invite', ticket: challengeId, expiresInSec: TICKET_TTL_SEC });
  })

  /**
   * Does this account have a number attached, and is it therefore recoverable?
   *
   * WHY THIS EXISTS. Phone sign-in only appears to a device with no token, so every
   * account that predates it -- including the one holding all the dogfooding data --
   * had no way to attach a number at all. Those accounts stay permanently
   * unrecoverable, and rotating the signing key would strand them for good, which is
   * exactly the trap the feature was built to remove.
   *
   * Returns the fact and nothing else. Not the number, not a masked version of it:
   * the server cannot read it back, and a screen that wants to show one can show the
   * digits the person just typed.
   */
  .get('/v1/auth/phone', async (c) => {
    let ctx;
    try {
      ctx = await resolveCtx(c.req.header('authorization'));
    } catch (err) {
      if (err instanceof Unauthorized) return c.json({ error: 'unauthorized' }, 401);
      throw err;
    }
    const linked = await tenantSession(ctx, async (db) => {
      const { rows } = await db.query<{ n: string }>(
        `SELECT count(*) AS n FROM app_users
          WHERE id = $1 AND phone_hmac IS NOT NULL`, [ctx.userId]);
      return Number(rows[0]?.n ?? 0) > 0;
    });
    return c.json({ linked });
  })

  /**
   * Sign out, properly.
   *
   * There was no route for this at all. The app cleared its keychain and called it
   * done, which means the token it threw away kept working for anyone holding a copy
   * until it expired on its own -- up to a hundred and eighty days later. A sign-out
   * that only the signed-out device honours is not a sign-out.
   *
   * An UPDATE rather than a DELETE, on purpose. `revoked_at` is the column the read
   * path already checks on every request, the grant does not include DELETE, and a
   * deleted row destroys the record that the session ever existed -- which is the one
   * thing you want when working out how somebody got in.
   */
  .post('/v1/auth/logout', rateLimit('auth', LIMITS.auth), async (c) => {
    const header = c.req.header('authorization');
    let ctx;
    try {
      ctx = await resolveCtx(header);
    } catch (err) {
      // Already dead is the outcome asked for, so it is not an error.
      if (err instanceof Unauthorized) return c.json({ ok: true });
      throw err;
    }

    // Only the session that made this call. Signing out a phone must not sign out
    // the laptop -- "sign out everywhere" is a different, deliberate action.
    const sessionId = verifyToken((header ?? '').replace(/^Bearer\s+/i, '').trim());
    if (!sessionId) {
      // A legacy credential names no session, so there is nothing to revoke. Told
      // plainly rather than answered with a cheerful ok it does not deserve.
      return c.json({
        ok: false,
        error: 'not_revocable',
        message: 'This device is on the old credential. Update the app.',
      }, 409);
    }

    await tenantSession(ctx, (db) =>
      db.query(
        `UPDATE device_sessions SET revoked_at = now()
          WHERE id = $1 AND user_id = $2 AND revoked_at IS NULL`,
        [sessionId, ctx.userId],
      ));
    log.info({ userId: ctx.userId }, 'signed out');
    return c.json({ ok: true });
  })

  /** Dev only. Left in because turning it on is how the founder's own devices start. */
  .post('/v1/auth/device', rateLimit('signup', LIMITS.signup), async (c) => {
    if (!env.ALLOW_DEVICE_SIGNUP) {
      return c.json({ error: 'invite required', message: 'You need an invite code.' }, 403);
    }
    const body = (await c.req.json().catch(() => ({}))) as { label?: string };
    const provisioned = await provision(body.label ?? 'device');
    log.info({ userId: provisioned.userId }, 'device self-provisioned');
    return c.json({ token: provisioned.token, tenantId: provisioned.tenantId });
  });

/** Invites a signed-in person can hand out. Scarce on purpose. */
export const inviteRoutes = new Hono()
  .get('/v1/invites', async (c) => {
    let ctx;
    try {
      ctx = await resolveCtx(c.req.header('authorization'));
    } catch (err) {
      if (err instanceof Unauthorized) return c.json({ error: 'unauthorized' }, 401);
      throw err;
    }
    // Read through the owner pool: `invites` carries no RLS because a code must be
    // claimable by someone who is not yet anybody. The WHERE clause is the boundary,
    // and it is the only place this table is read by creator.
    const rows = await adminSession(async (db) => {
      const r = await db.query(
        `SELECT code, note, created_at, expires_at, (reserved_for IS NOT NULL) AS used
           FROM invites WHERE created_by = $1 ORDER BY created_at DESC LIMIT 50`,
        [ctx.userId],
      );
      return r.rows;
    });
    return c.json({ invites: rows, remaining: Math.max(0, env.INVITES_PER_USER - rows.filter((r) => !r.used).length) });
  })

  .post('/v1/invites', async (c) => {
    let ctx;
    try {
      ctx = await resolveCtx(c.req.header('authorization'));
    } catch (err) {
      if (err instanceof Unauthorized) return c.json({ error: 'unauthorized' }, 401);
      throw err;
    }
    const body = (await c.req.json().catch(() => ({}))) as { note?: string };

    const result = await adminSession(async (db) => {
      const { rows: open } = await db.query<{ n: string }>(
        `SELECT count(*) AS n FROM invites
          WHERE created_by = $1 AND reserved_for IS NULL AND expires_at > now()`,
        [ctx.userId],
      );
      if (Number(open[0]!.n) >= env.INVITES_PER_USER) return null;

      const code = mintInviteCode();
      await db.query(
        `INSERT INTO invites (code, created_by, note, expires_at)
         VALUES ($1,$2,$3, now() + ($4 || ' days')::interval)`,
        [code, ctx.userId, (body.note ?? '').slice(0, 200), String(env.INVITE_TTL_DAYS)],
      );
      return code;
    });

    if (!result) {
      return c.json({
        error: 'no invites left',
        message: `You can have ${env.INVITES_PER_USER} out at a time. Wait for one to be used.`,
      }, 429);
    }
    return c.json({ code: result, expiresInDays: env.INVITE_TTL_DAYS });
  });
