-- 0024: messaging between two matched people, and the safety surface around it.
--
-- Scope, decided deliberately. A dating DM is not WhatsApp, and the parts that make
-- WhatsApp hard -- end-to-end encryption, media pipelines, multi-device sync, group
-- membership, calls -- are absent from every dating app's first version too. What IS
-- non-negotiable for 1:1 text is here: idempotent sends, stable ordering, delivery and
-- read state, and the ability to make somebody stop.
--
-- THE RULE THAT SHAPES THE WHOLE TABLE: you can only message somebody through a
-- rendezvous where both agents agreed AND both humans agreed. There is no way to
-- address a message to an arbitrary user id, because `match_id` is the only routing
-- there is. Unsolicited contact is not policed, it is unrepresentable.
CREATE TABLE messages (
  id            uuid PRIMARY KEY,
  rendezvous_id uuid NOT NULL REFERENCES rendezvous(id) ON DELETE CASCADE,
  sender_id     uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  body          text NOT NULL CHECK (length(body) BETWEEN 1 AND 4000),

  -- Server clock, not the client's. A phone with a wrong clock would otherwise sort
  -- its own messages into last week.
  sent_at       timestamptz NOT NULL DEFAULT now(),
  -- Monotonic per conversation. Two messages inside the same millisecond still have a
  -- defined order, which a timestamp alone cannot promise.
  seq           bigint NOT NULL,

  delivered_at  timestamptz,
  read_at       timestamptz,
  -- Kept, never removed: "this message was deleted" is a message, and hard-deleting
  -- one silently rewrites a conversation somebody may need to report.
  redacted_at   timestamptz
);

-- The id is generated by the CLIENT, so a retry after a dropped response is the same
-- message rather than a second one. This is the whole of send idempotency.
CREATE UNIQUE INDEX messages_seq ON messages (rendezvous_id, seq);
CREATE INDEX messages_thread ON messages (rendezvous_id, sent_at DESC);
CREATE INDEX messages_unread ON messages (rendezvous_id, sender_id) WHERE read_at IS NULL;

-- Next sequence number for a conversation, allocated under the row lock so two
-- simultaneous sends cannot collide.
CREATE OR REPLACE FUNCTION next_message_seq(conversation uuid) RETURNS bigint
LANGUAGE sql AS $$
  SELECT coalesce(max(seq), 0) + 1 FROM messages WHERE rendezvous_id = conversation
$$;

-- ------------------------------------------------------------------ safety
--
-- Not optional, and not a later phase. An app that introduces strangers to each other
-- and has no way to make one of them stop is not finished, it is dangerous.

CREATE TABLE blocks (
  blocker_id  uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  blocked_id  uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (blocker_id, blocked_id),
  CONSTRAINT blocks_not_self CHECK (blocker_id <> blocked_id)
);

CREATE INDEX blocks_by_blocked ON blocks (blocked_id);

CREATE TABLE reports (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reporter_id   uuid NOT NULL REFERENCES app_users(id) ON DELETE SET NULL,
  reported_id   uuid NOT NULL REFERENCES app_users(id) ON DELETE SET NULL,
  rendezvous_id uuid REFERENCES rendezvous(id) ON DELETE SET NULL,
  reason        text NOT NULL,
  detail        text NOT NULL DEFAULT '',
  created_at    timestamptz NOT NULL DEFAULT now(),
  reviewed_at   timestamptz
);

CREATE INDEX reports_open ON reports (created_at DESC) WHERE reviewed_at IS NULL;

-- ---------------------------------------------------------------- isolation
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages FORCE ROW LEVEL SECURITY;
ALTER TABLE blocks   ENABLE ROW LEVEL SECURITY;
ALTER TABLE blocks   FORCE ROW LEVEL SECURITY;
ALTER TABLE reports  ENABLE ROW LEVEL SECURITY;
ALTER TABLE reports  FORCE ROW LEVEL SECURITY;

-- A message is readable by exactly the two people in its rendezvous. This is the one
-- place in the system where a row is legitimately visible across a tenant boundary,
-- and the boundary is the rendezvous rather than the tenant.
CREATE POLICY messages_participants ON messages FOR ALL
  USING (EXISTS (
    SELECT r.id FROM rendezvous r
     WHERE r.id = messages.rendezvous_id
       AND NULLIF(current_setting('app.user_id', true), '')::uuid IN (r.user_a, r.user_b)))
  WITH CHECK (
    sender_id = NULLIF(current_setting('app.user_id', true), '')::uuid
    AND EXISTS (
      SELECT r.id FROM rendezvous r
       WHERE r.id = messages.rendezvous_id
         AND NULLIF(current_setting('app.user_id', true), '')::uuid IN (r.user_a, r.user_b)
         -- Only an introduced pair. An agent-level yes is not permission to write to
         -- somebody, and the WITH CHECK is where that is enforced for good.
         AND r.status = 'introduced'));

CREATE POLICY blocks_mine ON blocks FOR ALL
  USING (blocker_id = NULLIF(current_setting('app.user_id', true), '')::uuid)
  WITH CHECK (blocker_id = NULLIF(current_setting('app.user_id', true), '')::uuid);

-- A report can be written and never read back. Somebody who could read their own
-- reports could confirm whether the other person had been actioned, which is a channel
-- straight back to the person they are trying to get away from.
CREATE POLICY reports_write_only ON reports FOR INSERT
  WITH CHECK (reporter_id = NULLIF(current_setting('app.user_id', true), '')::uuid);

GRANT SELECT, INSERT, UPDATE ON messages TO clone_app;
GRANT SELECT, INSERT, DELETE ON blocks   TO clone_app;
GRANT INSERT ON reports TO clone_app;
GRANT EXECUTE ON FUNCTION next_message_seq(uuid) TO clone_app;
