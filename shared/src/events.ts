/**
 * The wire contract between the Expo app and the server.
 *
 * Imported by BOTH sides. Changing a shape here breaks the client at compile time,
 * which is the entire reason the server is TypeScript.
 *
 * Transport is a single authenticated WebSocket, not SSE: `expo/fetch` streaming
 * still carries unshipped iOS fixes (empty body on a 200, dropped chunks, AbortSignal
 * hangs), while React Native's WebSocket is built in and stable.
 */
import { z } from 'zod';
import { Look } from './look.js';

/** Client-generated. THE idempotency key: a reconnect can never spawn a second LLM call. */
export const TurnId = z.uuid();
export const SessionId = z.uuid();

// ── Client -> server ────────────────────────────────────────────────────────
export const ClientHello = z.object({
  type: z.literal('hello'),
  sessionId: SessionId,
  /** Resume: server replays any completed turns the client missed. */
  lastSeenTurnId: TurnId.nullable(),
});

export const ClientTurn = z.object({
  type: z.literal('turn'),
  turnId: TurnId,
  sessionId: SessionId,
  text: z.string().min(1).max(16_000),
  source: z.enum(['text', 'voice']).default('text'),
  /**
   * ASR word-confidence, when source === 'voice'. NOT decoration: low-confidence
   * spans default the extracted fact's stance to 'hedged', because ASR is exactly
   * where hedges die ("I might", "kinda", "I guess") and no published memory
   * benchmark runs on ASR output at all.
   */
  asrConfidence: z.number().min(0).max(1).optional(),
  asrLowConfSpans: z.array(z.object({ start: z.number(), end: z.number() })).optional(),
});

/**
 * Messaging between two matched people, on the same socket as the clone conversation.
 *
 * One socket rather than two, because a second connection would need its own auth, its
 * own reconnect handling and its own offline queue -- three copies of the hard parts
 * for no gain. The discriminated union keeps them from ever being confused.
 */
export const ClientDm = z.object({
  type: z.literal('dm.send'),
  /** Generated by the CLIENT. A retry after a dropped response is the same message. */
  messageId: z.uuid(),
  rendezvousId: z.uuid(),
  text: z.string().min(1).max(4000),
});

export const ClientDmRead = z.object({
  type: z.literal('dm.read'),
  rendezvousId: z.uuid(),
});

export const ClientTyping = z.object({
  type: z.literal('dm.typing'),
  rendezvousId: z.uuid(),
  typing: z.boolean(),
});

/**
 * The park, live: real people walking in Cubbon Park at the same time see each other
 * and can talk to whoever is near.
 *
 * WHERE YOU ARE goes to the server a few times a second while you are in the park,
 * and to nobody further than the park's mist (PARK_VIEW). WHAT YOU SAY goes to the
 * people within PARK_EARSHOT of you and to nobody else, is kept by nobody (not written
 * anywhere), and is refused if it holds a phone number, a handle or a link -- those
 * are swapped after both say yes, as everywhere else in the app.
 */
export const PARK_SAY_MAX = 200;
/** How far a person in the park is sent to you, in park units (8.1 m each): the mist. */
export const PARK_VIEW = 45;
/** How far what you say carries: about twenty metres. */
export const PARK_EARSHOT = 2.5;

const ParkCoord = z.number().finite().min(-500).max(500);
export const ClientParkEnter = z.object({
  type: z.literal('park.enter'),
  /** "Talk with people nearby" on (park-voice.ts): off unless the person turned it on. */
  voiceOpen: z.boolean().optional(),
});
export const ClientParkLeave = z.object({ type: z.literal('park.leave') });
export const ClientParkMove = z.object({
  type: z.literal('park.move'),
  x: ParkCoord,
  z: ParkCoord,
  facing: z.number().finite(),
  moving: z.boolean(),
  /** On a bicycle (the app's bike.ts): the people near see you on one. */
  riding: z.boolean().optional(),
});
export const ClientParkSay = z.object({
  type: z.literal('park.say'),
  text: z.string().trim().min(1).max(PARK_SAY_MAX),
});

/**
 * Two people in the park who agree to talk (server park/pairs.ts). "Find someone"
 * asks the server for the best free person here -- most in common first -- who is
 * asked, and says yes or no. Nobody is asked while they are busy: talking with
 * somebody, asking, or being asked. A pair may take a bench: while they sit, what
 * they say goes to each other and to nobody else, and nothing said near them reaches
 * them.
 */
export const ClientParkFind = z.object({ type: z.literal('park.find') });
export const ClientParkAnswer = z.object({ type: z.literal('park.answer'), yes: z.boolean() });
/** Stop asking, or stop talking: whichever you are doing. */
export const ClientParkPart = z.object({ type: z.literal('park.part') });
/** A bench by its number in the park's own list (garden benches, the same on every phone). */
export const ClientParkSit = z.object({ type: z.literal('park.sit'), bench: z.number().int().min(0).max(10_000) });
export const ClientParkStand = z.object({ type: z.literal('park.stand') });
/**
 * The phone lost the voice server and its own retries gave up: a fresh voice pass, please,
 * for where it is now (server park/voice.ts). The old one may have run out.
 */
export const ClientParkVoiceAgain = z.object({ type: z.literal('park.voice_again') });
/**
 * "Talk with people nearby", on or off (server park/room.ts): strangers hear each other
 * only when both have it on. The one you are talking with, you hear either way.
 */
export const ClientParkVoiceOpen = z.object({ type: z.literal('park.voice_open'), open: z.boolean() });

export const ClientMessage = z.discriminatedUnion('type', [
  ClientHello, ClientTurn, ClientDm, ClientDmRead, ClientTyping,
  ClientParkEnter, ClientParkLeave, ClientParkMove, ClientParkSay,
  ClientParkFind, ClientParkAnswer, ClientParkPart, ClientParkSit, ClientParkStand, ClientParkVoiceAgain,
  ClientParkVoiceOpen,
]);
export type ClientMessage = z.infer<typeof ClientMessage>;

// ── Server -> client ────────────────────────────────────────────────────────
// Mirrors the closed streaming event set the LLM port normalises to (see
// server/src/llm/port.ts). Adding a case here is a deliberate protocol change.

const DmMessage = z.object({
  id: z.uuid(),
  rendezvousId: z.uuid(),
  senderId: z.uuid(),
  text: z.string(),
  sentAt: z.string(),
  seq: z.string(),
  deliveredAt: z.string().nullable(),
  readAt: z.string().nullable(),
});

/** A per-viewer handle for somebody in the square. 32 hex; never a user id. */
const AgentRef = z.string().regex(/^[0-9a-f]{32}$/);

/**
 * Somebody in the park right now, as you are allowed to see them: where they stand
 * and how they look, under the same per-viewer ref the square gives them -- so the
 * app can put the person in place of their agent, never both.
 */
export const ParkPerson = z.object({
  ref: AgentRef,
  x: z.number(),
  z: z.number(),
  facing: z.number(),
  moving: z.boolean(),
  /** Sent the first time you are sent them, and when it changes: four times a second
   *  over a slow tunnel, a whole look per person per frame was most of the bytes. */
  look: Look.optional(),
  /** On a bench with somebody, and not walking to it: drawn sitting. */
  sitting: z.boolean().optional(),
  /** On a bicycle: drawn riding one. */
  riding: z.boolean().optional(),
  /** Within earshot: who they are to the voice server, to listen to them (server park/voice.ts). */
  voice: z.string().optional(),
});
export type ParkPerson = z.infer<typeof ParkPerson>;

export const ServerEvent = z.discriminatedUnion('type', [
  /** A message, echoed to the sender and pushed to the recipient. */
  z.object({ type: z.literal('dm.message'), message: DmMessage }),
  /** Delivery and read receipts, by message id. */
  z.object({
    type: z.literal('dm.receipt'),
    rendezvousId: z.uuid(),
    messageIds: z.array(z.uuid()),
    state: z.enum(['delivered', 'read']),
  }),
  z.object({ type: z.literal('dm.typing'), rendezvousId: z.uuid(), typing: z.boolean() }),
  /** The send was refused. Sent only to the sender, and never says why to the other. */
  z.object({ type: z.literal('dm.rejected'), messageId: z.uuid(), reason: z.string() }),
  z.object({ type: z.literal('turn.accepted'), turnId: TurnId }),
  /** Sent instead of streaming when this turnId was already completed. Idempotency. */
  z.object({ type: z.literal('turn.replayed'), turnId: TurnId, text: z.string() }),
  z.object({ type: z.literal('text.delta'), turnId: TurnId, text: z.string() }),
  z.object({ type: z.literal('turn.done'), turnId: TurnId, text: z.string() }),
  /**
   * The conflicts queue surfacing itself. This is the PRIMARY user-facing quality
   * mechanism, not a fallback: a clone that asks "you mentioned prawn curry - should
   * I update your shellfish note?" is measurably better than one that silently
   * guesses right half the time, and it is the only thing in the design that turns a
   * wrong answer into a logged, resolvable event.
   */
  z.object({
    type: z.literal('conflict.question'),
    conflictId: z.uuid(),
    question: z.string(),
  }),
  // ── the town ──────────────────────────────────────────────────────────
  // What the square is allowed to draw, and nothing more: refs, never ids; no names,
  // no text anybody wrote, and no verdict of any kind -- not a number and not words
  // either. Every event here also reaches the app by the next poll of /v1/world --
  // the socket is the animation cue, the roster is the truth.
  z.object({ type: z.literal('round.queued'), roundId: z.uuid() }),
  /** Your agent is walking over to somebody. `roundId` is null on the visited side. */
  z.object({
    type: z.literal('round.met'), roundId: z.uuid().nullable(), rendezvousId: z.uuid(),
    agent: AgentRef, practice: z.boolean(),
  }),
  z.object({
    type: z.literal('round.talking'), roundId: z.uuid().nullable(), rendezvousId: z.uuid(),
    agent: AgentRef,
  }),
  /**
   * The pair is written and the card exists: the agents "met". It says nothing about
   * how it went. It used to carry `agreement` -- got_on / unsure / did_not_click --
   * and the square drew it as a tick or a cross over both heads.
   */
  z.object({
    type: z.literal('round.decided'), roundId: z.uuid().nullable(), rendezvousId: z.uuid(),
    agent: AgentRef,
  }),
  z.object({
    type: z.literal('round.done'), roundId: z.uuid(), met: z.number(),
    skipped: z.string().nullable(), error: z.string().nullable(),
  }),
  /** Sent to the second mover, and only once the first has said YES. Never on a no. */
  z.object({ type: z.literal('match.turn'), rendezvousId: z.uuid(), agent: AgentRef }),
  /** Both said yes. Sent to both. */
  z.object({ type: z.literal('match.introduced'), rendezvousId: z.uuid(), agent: AgentRef }),

  /** The photo check finished. To the person who asked for it, only. */
  z.object({
    type: z.literal('photos.checked'),
    result: z.enum(['match', 'no_match', 'no_face', 'not_live', 'no_photos', 'error']),
  }),

  // ── the park, live ────────────────────────────────────────────────────
  /** Everybody within PARK_VIEW of you, a few times a second, you excluded. */
  z.object({ type: z.literal('park.people'), people: z.array(ParkPerson) }),
  /** Something said within earshot. `you` when it was you, so it shows over your head. */
  z.object({
    type: z.literal('park.said'), ref: z.union([AgentRef, z.literal('you')]), text: z.string(), at: z.number(),
    /** Said on a bench: to the two of you and nobody else. */
    private: z.boolean().optional(),
  }),
  /** What you said was not sent, and why: to you, only. */
  z.object({
    type: z.literal('park.refused'),
    reason: z.enum(['contact', 'too_fast', 'not_in_park']),
  }),
  /**
   * How "Find someone" is going, to the person looking. `asking` names who (their ref)
   * and what you share, when you share something either of you made public.
   */
  z.object({
    type: z.literal('park.finding'),
    status: z.enum(['asking', 'nobody', 'declined', 'no_answer', 'busy', 'gone']),
    ref: AgentRef.optional(),
    why: z.string().optional(),
  }),
  /** Somebody here would like to talk to you. Answer with park.answer. */
  z.object({ type: z.literal('park.asked'), ref: AgentRef, why: z.string().optional() }),
  /** They stopped asking, or the time ran out. */
  z.object({ type: z.literal('park.unasked') }),
  /** You are talking with them now: where they stand, for the ride over. */
  z.object({ type: z.literal('park.paired'), ref: AgentRef, x: z.number(), z: z.number(), asked: z.boolean() }),
  /** It ended: either of you, or one of you left the park. */
  z.object({ type: z.literal('park.parted') }),
  /** The bench is yours: walk there and sit. Private from now on. */
  z.object({ type: z.literal('park.sat'), bench: z.number().int() }),
  /** Up off the bench: what you say is heard nearby again. */
  z.object({ type: z.literal('park.stood') }),
  /** That bench is taken. */
  z.object({ type: z.literal('park.bench_taken'), bench: z.number().int() }),
  /**
   * A pass to the voice server's room: the park's on walking in (and on getting up off a
   * bench), the two's own on a bench. canTalk false with `until`: reported for voice too
   * often, the mic is off until then (server park/voice.ts VOICE_BAN).
   */
  z.object({
    type: z.literal('park.voice'),
    url: z.string(), room: z.string(), token: z.string(), identity: z.string(),
    /** A bench's own room: only the two of them in it. */
    bench: z.boolean(),
    canTalk: z.boolean(), until: z.string().optional(),
  }),
  /**
   * What you have done together in the park today, and how far along the rest are
   * (shared/park-quests.ts; the server's park/quests.ts decides). `just` is the one
   * just done: what it was, the points it paid you, and your balance after.
   */
  z.object({
    type: z.literal('park.quests'),
    day: z.string(),
    done: z.array(z.enum(['hello', 'walk', 'ride', 'talk', 'sights'])),
    progress: z.record(z.string(), z.number()),
    sights: z.array(z.string()),
    just: z.object({ quest: z.enum(['hello', 'walk', 'ride', 'talk', 'sights']), points: z.number().int(), balance: z.number().int() }).optional(),
    /** Your points, when the server has just read them: on walking in, and with a payment. */
    balance: z.number().int().optional(),
  }),

  z.object({ type: z.literal('heartbeat') }),
  z.object({
    type: z.literal('error'),
    code: z.enum([
      'budget_exceeded',
      'rate_limited',
      'unsupported_capability',
      'unauthorized',
      'internal',
    ]),
    message: z.string(),
    retryable: z.boolean(),
  }),
]);
export type ServerEvent = z.infer<typeof ServerEvent>;

/** Server -> client heartbeat cadence. Client reconnects after 2 missed. */
export const HEARTBEAT_MS = 15_000;
